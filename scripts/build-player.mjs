import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceRoot = resolve(root, 'src');
const marker = '<!-- PLAYER_SCRIPT -->';
const names = '[A-Za-z_$][\\w$]*';

// The player uses named, relative imports and declaration exports only.
// Keep each module in its own scope and fail the build on unsupported syntax.
export function buildPlayer() {
  const modules = new Map();
  const visiting = new Set();

  function collect(file) {
    if (visiting.has(file)) throw new Error(`Player import cycle: ${file}`);
    if (modules.has(file)) return modules.get(file).id;
    const name = relative(sourceRoot, file);
    if (name.startsWith(`..${sep}`) || isAbsolute(name) || !name.endsWith('.js')) {
      throw new Error(`Invalid player module path: ${file}`);
    }
    visiting.add(file);
    const source = readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
    const exports = [];
    const body = source
      .replace(/^import \{([^{}\n]+)\} from ['"](\.{1,2}\/[^'"]+)['"];$/gm, (_, bindings, dependency) => {
        const imported = bindings.split(',').map(binding => binding.trim());
        if (imported.some(binding => !new RegExp(`^${names}$`).test(binding))) {
          throw new Error(`Unsupported player import in ${name}`);
        }
        const id = collect(resolve(dirname(file), dependency));
        return `const { ${imported.join(', ')} } = playerModules[${id}];`;
      })
      .replace(new RegExp(`^export (const|function) (${names})\\b`, 'gm'), (_, kind, exported) => {
        exports.push(exported);
        return `${kind} ${exported}`;
      });
    if (/^\s*(?:import|export)\b/m.test(body) || /\bimport\s*\(/.test(body)) {
      throw new Error(`Unsupported module syntax in ${name}`);
    }
    visiting.delete(file);
    const id = modules.size;
    modules.set(file, { id, name: name.split(sep).join('/'), body: body.trimEnd(), exports });
    return id;
  }

  collect(resolve(sourceRoot, 'main.js'));
  const sections = [...modules.values()].map(({ id, name, body, exports }) =>
    `// ${name}\nplayerModules[${id}] = (() => {\n${body}\nreturn { ${exports.join(', ')} };\n})();`);
  const script = `'use strict';\ndocument.addEventListener('DOMContentLoaded', () => {\nconst playerModules = [];\n${sections.join('\n\n')}\n}, { once: true });`;
  if (/<\/script\b/i.test(script)) throw new Error('Unexpected script end tag in player code');
  const template = readFileSync(resolve(sourceRoot, 'index.template.html'), 'utf8').replaceAll('\r\n', '\n');
  if (template.split(marker).length !== 2) throw new Error('Expected exactly one player script placeholder');
  return template.replace(marker, () =>
    `<!-- Generated by npm run build from src/index.template.html and the player modules. -->\n  <script>\n${script}\n  </script>`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  writeFileSync(resolve(root, 'index.html'), buildPlayer(), 'utf8');
}
